import { beforeEach, describe, expect, it, vi } from "vitest";

import { render, screen, waitFor } from "@testing-library/react";

import userEvent from "@testing-library/user-event";

import { createInitialWorkspace } from "../reducers/workspaceReducer";

import CodeGenerator from "./CodeGenerator";

const { copyCodeToClipboardMock, exportCodeMock } = vi.hoisted(() => ({
  copyCodeToClipboardMock: vi.fn(),
  exportCodeMock: vi.fn(),
}));

vi.mock("../utils/codeExport", () => ({
  copyCodeToClipboard: copyCodeToClipboardMock,
  exportCode: exportCodeMock,
}));

function createComponentData(componentId, updates = {}) {
  const initialData = createInitialWorkspace().components[componentId];

  return {
    ...initialData,
    ...updates,
    content: {
      ...initialData.content,
      ...(updates.content ?? {}),
    },
    styles: {
      ...initialData.styles,
      ...(updates.styles ?? {}),
    },
  };
}

function renderCodeGenerator({
  componentId = "button",
  componentData = createComponentData("button"),
  activeStyleState = "normal",
} = {}) {
  return render(
    <CodeGenerator
      componentId={componentId}
      componentData={componentData}
      activeStyleState={activeStyleState}
    />,
  );
}

describe("CodeGenerator component", () => {
  beforeEach(() => {
    vi.clearAllMocks();

    copyCodeToClipboardMock.mockResolvedValue(true);

    exportCodeMock.mockReturnValue({
      fileName: "button.jsx",
      mimeType: "text/javascript;charset=utf-8",
    });
  });

  it("renders format selection and Copy and Export buttons", () => {
    renderCodeGenerator();

    expect(screen.getByLabelText("Code format")).toHaveValue("jsx");

    expect(screen.getByRole("button", { name: "Copy" })).toBeInTheDocument();

    expect(screen.getByRole("button", { name: "Export" })).toBeInTheDocument();

    expect(screen.getByLabelText("Generated code")).toHaveTextContent(
      "GeneratedButton",
    );
  });

  it("copies the exact code currently displayed", async () => {
    const user = userEvent.setup();

    renderCodeGenerator();

    const displayedCode = screen.getByLabelText("Generated code").textContent;

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(copyCodeToClipboardMock).toHaveBeenCalledOnce();

    expect(copyCodeToClipboardMock).toHaveBeenCalledWith(displayedCode);

    expect(await screen.findByRole("status")).toHaveTextContent(
      "Code copied successfully!",
    );
  });

  it("displays an accessible error when Copy fails", async () => {
    const user = userEvent.setup();

    copyCodeToClipboardMock.mockRejectedValueOnce(
      new Error("Permission denied"),
    );

    renderCodeGenerator();

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(await screen.findByRole("alert")).toHaveTextContent(
      "Unable to copy code.",
    );
  });

  it("updates the displayed and copied code when the format changes", async () => {
    const user = userEvent.setup();

    renderCodeGenerator();

    const formatSelect = screen.getByLabelText("Code format");

    await user.selectOptions(formatSelect, "css");

    const displayedCss = screen.getByLabelText("Generated code").textContent;

    expect(displayedCss).toContain("Generated by StyleLab - button");

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(copyCodeToClipboardMock).toHaveBeenCalledWith(displayedCss);

    await user.selectOptions(formatSelect, "tailwind");

    expect(screen.getByLabelText("Generated code")).toHaveTextContent(
      "inline-flex",
    );
  });

  it("exports the exact displayed code using the selected component and format", async () => {
    const user = userEvent.setup();

    exportCodeMock.mockReturnValueOnce({
      fileName: "card.css",
      mimeType: "text/css;charset=utf-8",
    });

    renderCodeGenerator({
      componentId: "card",
      componentData: createComponentData("card", {
        layout: "left",
      }),
    });

    await user.selectOptions(screen.getByLabelText("Code format"), "css");

    const displayedCode = screen.getByLabelText("Generated code").textContent;

    await user.click(screen.getByRole("button", { name: "Export" }));

    expect(exportCodeMock).toHaveBeenCalledOnce();

    expect(exportCodeMock).toHaveBeenCalledWith({
      code: displayedCode,
      componentId: "card",
      format: "css",
    });

    expect(await screen.findByRole("status")).toHaveTextContent("card.css");
  });

  it("displays an accessible error when Export fails", async () => {
    const user = userEvent.setup();

    exportCodeMock.mockImplementationOnce(() => {
      throw new Error("Download failed");
    });

    renderCodeGenerator();

    await user.click(screen.getByRole("button", { name: "Export" }));

    expect(await screen.findByRole("alert")).toHaveTextContent(
      "Unable to export code.",
    );
  });

  it("uses the latest component content after the component data changes", async () => {
    const user = userEvent.setup();

    const initialData = createComponentData("button", {
      content: { label: "First label" },
    });

    const { rerender } = renderCodeGenerator({
      componentId: "button",
      componentData: initialData,
    });

    expect(screen.getByLabelText("Generated code")).toHaveTextContent(
      "First label",
    );

    const updatedData = createComponentData("button", {
      content: { label: "Latest label" },
    });

    rerender(
      <CodeGenerator
        componentId="button"
        componentData={updatedData}
        activeStyleState="normal"
      />,
    );

    const displayedCode = screen.getByLabelText("Generated code").textContent;

    expect(displayedCode).toContain("Latest label");

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(copyCodeToClipboardMock).toHaveBeenCalledWith(displayedCode);
  });

  it("clears previous feedback when the generated code changes", async () => {
    const user = userEvent.setup();

    const initialData = createComponentData("button");

    const { rerender } = renderCodeGenerator({
      componentId: "button",
      componentData: initialData,
    });

    await user.click(screen.getByRole("button", { name: "Copy" }));

    expect(await screen.findByRole("status")).toBeInTheDocument();

    const updatedData = createComponentData("button", {
      content: { label: "Updated button" },
    });

    rerender(
      <CodeGenerator
        componentId="button"
        componentData={updatedData}
        activeStyleState="normal"
      />,
    );

    await waitFor(() => {
      expect(screen.queryByRole("status")).not.toBeInTheDocument();
    });
  });

  it("does not modify Workspace data during Copy and Export", async () => {
    const user = userEvent.setup();

    const componentData = createComponentData("button");
    const originalData = JSON.parse(JSON.stringify(componentData));

    renderCodeGenerator({
      componentId: "button",
      componentData,
    });

    await user.click(screen.getByRole("button", { name: "Copy" }));

    await user.click(screen.getByRole("button", { name: "Export" }));

    expect(componentData).toEqual(originalData);
  });
});
